using System;

    
    public class Performer {
        
                
                private string name;
                private int age;
                
                public Performer(string name, int age){
                    this.name=name;
                    this.age=age;
                }
                
                public string GetName(){
                    return name;
                }
                
                
                public int GetAge(){
                    return age;
                }
                
        }
        
 
